package it.refertoelettronico.model

/** Local id is independent of names and the optional eScoreVolley source identifier. */
data class StaffCandidate(val id:String,val sourceId:String?=null,val name:String="",val roleCode:String="",val roleLabel:String="",
    val scope:String="UNKNOWN",val assignment:String="UNMAPPED",val selected:Boolean=false)

object StaffReview {
    val labels=linkedMapOf("UNMAPPED" to "Da mappare", "COACH" to "Allenatore", "ASSISTANT" to "Vice allenatore",
        "PHYSIO" to "Fisioterapista","DOCTOR" to "Medico","MANAGER" to "Dirigente", "SCORER" to "Segnapunti di gara","ATTENDANT" to "Addetto all’arbitro")
    val bench=listOf("COACH","ASSISTANT","PHYSIO","DOCTOR","MANAGER")
    fun scope(role:String)=when(role){in bench->"BENCH";"SCORER","ATTENDANT"->"SERVICE";else->"UNKNOWN"}
    fun suggested(code:String,receivedScope:String):String {
        val role=when(code){"TEC1"->"COACH";"TEC2"->"ASSISTANT";"DIRAU"->"MANAGER";"DIRS"->"SCORER";"DIRAA"->"ATTENDANT";else->"UNMAPPED"}
        return role.takeIf{scope(it)==receivedScope} ?: "UNMAPPED"
    }
    fun issues(config:MatchConfig):Map<String,String> {
        val selected=config.teams.flatMapIndexed{t,team->team.staffRoster.orEmpty().filter{it.selected}.map{t to it}}
        val errors=linkedMapOf<String,String>()
        selected.forEach{(_,p)->
            if(p.assignment !in labels || p.assignment=="UNMAPPED" || scope(p.assignment)!=p.scope)errors[p.id]="Mappa il ruolo e l’ambito oppure deseleziona questa proposta."
            if(p.name.isBlank())errors[p.id]="Completa il nome dell’incaricato."
        }
        selected.groupBy{(t,p)->if(p.scope=="SERVICE")"gara:${p.assignment}" else "$t:${p.assignment}"}.values.filter{it.size>1}.flatten().forEach{(_,p)->errors[p.id]="Scegli una sola persona per questo incarico."}
        selected.filter{!it.second.sourceId.isNullOrBlank()}.groupBy{it.second.sourceId}.values.filter{it.size>1}.flatten().forEach{(_,p)->errors[p.id]="La stessa persona ha più incarichi selezionati: conferma un solo ruolo."}
        return errors
    }
    /** Remove values generated by a previous confirmation before editing its proposals again. */
    fun prepare(config:MatchConfig):MatchConfig {
        var result=config
        config.teams.forEachIndexed{t,team->team.staffRoster.orEmpty().filter{it.selected}.forEach{p->
            val index=bench.indexOf(p.assignment)
            if(index>=0 && result.teams[t].staff.getOrElse(index){""}==p.name.trim()) {
                val next=result.teams[t].copy(staff=result.teams[t].staff.mapIndexed{i,s->if(i==index)""else s})
                result=result.copy(teams=result.teams.mapIndexed{i,s->if(i==t)next else s})
            }
            if(p.assignment=="SCORER" && result.officials.getOrElse(2){""}==p.name.trim())result=result.copy(officials=result.officials.mapIndexed{i,s->if(i==2)""else s})
            if(p.assignment=="ATTENDANT" && result.refereeAttendant==p.name.trim())result=result.copy(refereeAttendant=null)
        }}
        return result
    }
    fun confirm(config:MatchConfig):MatchConfig {
        require(issues(config).isEmpty()){issues(config).values.first()}
        var result=config
        config.teams.forEachIndexed{t,team->team.staffRoster.orEmpty().filter{it.selected}.forEach{p->
            val index=bench.indexOf(p.assignment)
            if(index>=0)result=result.copy(teams=result.teams.mapIndexed{i,s->if(i==t)s.copy(staff=List(5){j->if(j==index)p.name.trim()else s.staff.getOrElse(j){""}})else s})
            if(p.assignment=="SCORER")result=result.copy(officials=List(7){i->if(i==2)p.name.trim()else result.officials.getOrElse(i){""}})
            if(p.assignment=="ATTENDANT")result=result.copy(refereeAttendant=p.name.trim())
        }}
        return result
    }
}
